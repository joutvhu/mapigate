#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const CHUNK_SIZE = 40;

const JS_RESERVED = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger", "default",
  "delete", "do", "else", "export", "extends", "finally", "for", "function",
  "if", "import", "in", "instanceof", "new", "return", "super", "switch",
  "this", "throw", "try", "typeof", "var", "void", "while", "with", "yield"
]);

function toSafeVar(id, prefix = "p") {
  const cleaned = id.replace(/[^a-zA-Z0-9]/g, "_");
  if (/^[0-9]/.test(cleaned) || JS_RESERVED.has(cleaned)) {
    return `${prefix}_${cleaned}`;
  }
  return cleaned;
}

function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
}

function generateProviders() {
  const providersDir = path.join(rootDir, "src", "providers");
  const generatedDir = path.join(providersDir, "generated");
  const chunksDir = path.join(generatedDir, "chunks");
  const runtimeDir = path.join(generatedDir, "runtime");

  fs.mkdirSync(chunksDir, { recursive: true });
  fs.mkdirSync(runtimeDir, { recursive: true });
  for (const f of fs.readdirSync(chunksDir)) {
    fs.unlinkSync(path.join(chunksDir, f));
  }
  for (const f of fs.readdirSync(runtimeDir)) {
    fs.unlinkSync(path.join(runtimeDir, f));
  }

  const categories = ["runtime", "composite", "catalog"];
  const providers = [];
  const seenIds = new Set();

  for (const cat of categories) {
    const catDir = path.join(providersDir, cat);
    if (!fs.existsSync(catDir)) continue;
    const entries = fs.readdirSync(catDir, { withFileTypes: true });
    for (const entry of entries) {
      if (entry.isDirectory()) {
        const metaPath = path.join(catDir, entry.name, "metadata.ts");
        const provPath = path.join(catDir, entry.name, "provider.ts");
        if (fs.existsSync(metaPath) && fs.existsSync(provPath)) {
          providers.push({ id: entry.name, category: cat });
          seenIds.add(entry.name);
        }
      }
    }
  }

  providers.sort((a, b) => a.id.localeCompare(b.id));

  console.log(`[codegen] Found ${providers.length} provider modules in src/providers/`);

  // 1. Generate Metadata Chunks
  const chunkCount = Math.ceil(providers.length / CHUNK_SIZE);
  const metadataChunkNames = [];

  for (let i = 0; i < chunkCount; i++) {
    const chunkName = `chunk${i + 1}`;
    metadataChunkNames.push(chunkName);
    const chunkProviders = providers.slice(i * CHUNK_SIZE, (i + 1) * CHUNK_SIZE);

    const importLines = chunkProviders.map((p) => {
      const varName = toSafeVar(p.id);
      const relPath = p.category ? `../../${p.category}/${p.id}/metadata.js` : `../../${p.id}/metadata.js`;
      return `import { metadata as ${varName} } from "${relPath}";`;
    });

    const recordLines = chunkProviders.map((p) => {
      const varName = toSafeVar(p.id);
      return `  "${p.id}": ${varName},`;
    });

    const chunkContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { ProviderRegistryItem } from "../../core/types.js";

${importLines.join("\n")}

export const metadataChunk${i + 1}: Record<string, ProviderRegistryItem> = {
${recordLines.join("\n")}
};
`;

    fs.writeFileSync(path.join(chunksDir, `${chunkName}.ts`), chunkContent, "utf8");
  }

  // 2. Generate aggregated metadata registry
  const metaImports = metadataChunkNames.map(
    (name, idx) => `import { metadataChunk${idx + 1} } from "./chunks/${name}.js";`
  );
  const metaSpreads = metadataChunkNames.map(
    (_, idx) => `  ...metadataChunk${idx + 1},`
  );

  const metaRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { ProviderRegistryItem } from "../core/types.js";

${metaImports.join("\n")}

export const PROVIDER_REGISTRY: Record<string, ProviderRegistryItem> = {
${metaSpreads.join("\n")}
};
`;
  fs.writeFileSync(
    path.join(generatedDir, "metadataRegistry.generated.ts"),
    metaRegistryContent,
    "utf8"
  );

  // 3. Generate Runtime Registration Chunks
  const runtimeChunkNames = [];

  for (let i = 0; i < chunkCount; i++) {
    const chunkName = `chunk${i + 1}`;
    runtimeChunkNames.push(chunkName);
    const chunkProviders = providers.slice(i * CHUNK_SIZE, (i + 1) * CHUNK_SIZE);

    const importLines = chunkProviders.map((p) => {
      const varName = `Prov_${toSafeVar(p.id)}`;
      const relPath = p.category ? `../../${p.category}/${p.id}/provider.js` : `../../${p.id}/provider.js`;
      return `import ${varName} from "${relPath}";`;
    });

    const registerCalls = chunkProviders.map((p) => {
      const varName = `Prov_${toSafeVar(p.id)}`;
      return `  registry.register(new ${varName}());`;
    });

    const chunkContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY

${importLines.join("\n")}

export function registerRuntimeChunk${i + 1}(registry: { register(p: any): void }): void {
${registerCalls.join("\n")}
}
`;

    fs.writeFileSync(path.join(runtimeDir, `${chunkName}.ts`), chunkContent, "utf8");
  }

  // 4. Generate aggregated providers registry
  const runtimeImports = runtimeChunkNames.map(
    (name, idx) => `import { registerRuntimeChunk${idx + 1} } from "./runtime/${name}.js";`
  );
  const runtimeCalls = runtimeChunkNames.map(
    (_, idx) => `  registerRuntimeChunk${idx + 1}(registry);`
  );

  const runtimeRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import { PROVIDER_REGISTRY } from "./metadataRegistry.generated.js";

${runtimeImports.join("\n")}

export { PROVIDER_REGISTRY };

export function registerAllGeneratedProviders(registry: { register(p: any, aliases?: string[]): void }): void {
${runtimeCalls.join("\n")}
}
`;
  fs.writeFileSync(
    path.join(generatedDir, "providersRegistry.ts"),
    runtimeRegistryContent,
    "utf8"
  );
}

function generateMitmHandlers() {
  const handlersDir = path.join(rootDir, "src", "mitm", "handlers");
  const generatedDir = path.join(handlersDir, "generated");

  fs.mkdirSync(generatedDir, { recursive: true });

  const entries = fs.readdirSync(handlersDir, { withFileTypes: true });
  const toolFolders = entries
    .filter((e) => e.isDirectory() && e.name !== "generated")
    .map((e) => e.name)
    .filter((name) => {
      const configPath = path.join(handlersDir, name, "config.ts");
      const handlerPath = path.join(handlersDir, name, "handler.ts");
      return fs.existsSync(configPath) && fs.existsSync(handlerPath);
    })
    .sort();

  console.log(`[codegen] Found ${toolFolders.length} MITM tool modules in src/mitm/handlers/`);

  // 1. Generate toolsConfig.ts
  const toolImports = toolFolders.map((t) => {
    return `import { toolConfig as ${toSafeVar(t)}Config } from "../${t}/config.js";`;
  });

  const toolElements = toolFolders.map((t) => `  ${toSafeVar(t)}Config,`);

  const toolsConfigContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { MitmToolConfig } from "../../types.js";

${toolImports.join("\n")}

export const MITM_TOOLS: MitmToolConfig[] = [
${toolElements.join("\n")}
];
`;

  fs.writeFileSync(path.join(generatedDir, "toolsConfig.ts"), toolsConfigContent, "utf8");

  // 2. Generate handlersRegistry.ts
  const handlerImports = toolFolders.map((t) => {
    const clsName = `${toPascalCase(t)}MitmHandler`;
    return `import { ${clsName} } from "../${t}/handler.js";`;
  });

  const handlerRegisters = toolFolders.map((t) => {
    const clsName = `${toPascalCase(t)}MitmHandler`;
    return `  registry.register(new ${clsName}());`;
  });

  const handlersRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { MitmHandlerRegistry } from "../../registry.js";
${handlerImports.join("\n")}
import { DefaultPassthroughMitmHandler } from "../defaultPassthrough.js";

export function registerAllMitmHandlers(registry: typeof MitmHandlerRegistry): void {
${handlerRegisters.join("\n")}
  registry.register(new DefaultPassthroughMitmHandler());
}
`;

  fs.writeFileSync(
    path.join(generatedDir, "handlersRegistry.ts"),
    handlersRegistryContent,
    "utf8"
  );

  // 3. Generate index.ts
  const toolReExports = toolFolders.map((t) => `export * from "./${t}/index.js";`);

  const indexContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
export * from "./base.js";
export * from "./defaultPassthrough.js";
export * from "./generated/handlersRegistry.js";
${toolReExports.join("\n")}
`;

  fs.writeFileSync(path.join(handlersDir, "index.ts"), indexContent, "utf8");
}

function generateCliTools() {
  const toolsDir = path.join(rootDir, "src", "cli", "tools");
  const defsDir = path.join(toolsDir, "definitions");
  const generatedDir = path.join(toolsDir, "generated");

  fs.mkdirSync(generatedDir, { recursive: true });

  const entries = fs.readdirSync(defsDir, { withFileTypes: true });
  const toolFolders = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .filter((name) => {
      const defPath = path.join(defsDir, name, "definition.ts");
      return fs.existsSync(defPath);
    })
    .sort();

  console.log(`[codegen] Found ${toolFolders.length} CLI tool modules in src/cli/tools/definitions/`);

  // 1. Generate toolsRegistry.ts
  const toolImports = toolFolders.map((t) => {
    return `import { definition as ${toSafeVar(t, "tool")}Def } from "../definitions/${t}/definition.js";`;
  });

  const toolElements = toolFolders.map((t) => `  "${t}": ${toSafeVar(t, "tool")}Def,`);

  const toolsRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { CliToolDefinition } from "../types.js";

${toolImports.join("\n")}

export const CLI_TOOLS: Record<string, CliToolDefinition> = {
${toolElements.join("\n")}
};

export const CLI_TOOLS_ARRAY: CliToolDefinition[] = Object.values(CLI_TOOLS);
`;

  fs.writeFileSync(path.join(generatedDir, "toolsRegistry.ts"), toolsRegistryContent, "utf8");

  // 2. Generate handlersRegistry.ts
  const configuratorTools = toolFolders.filter((t) => {
    const configPath = path.join(defsDir, t, "configurator.ts");
    return fs.existsSync(configPath);
  });

  const handlerImports = configuratorTools.map((t) => {
    return `import ${toSafeVar(t, "tool")}Handler from "../definitions/${t}/configurator.js";`;
  });

  const handlerElements = configuratorTools.map((t) => `  ${toSafeVar(t, "tool")}Handler,`);

  const handlersRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { ToolConfigHandler } from "../types.js";

${handlerImports.join("\n")}

export const ALL_TOOL_HANDLERS: ToolConfigHandler[] = [
${handlerElements.join("\n")}
];
`;

  fs.writeFileSync(path.join(generatedDir, "handlersRegistry.ts"), handlersRegistryContent, "utf8");
}

function generateProviderRoutes() {
  const providersDir = path.join(rootDir, "src", "providers");
  const generatedDir = path.join(providersDir, "generated");

  fs.mkdirSync(generatedDir, { recursive: true });

  const categories = ["runtime", "composite", "catalog"];
  const routeProviders = [];
  const seenRouteIds = new Set();

  for (const cat of categories) {
    const catDir = path.join(providersDir, cat);
    if (!fs.existsSync(catDir)) continue;
    const entries = fs.readdirSync(catDir, { withFileTypes: true });
    for (const entry of entries) {
      if (entry.isDirectory()) {
        const routePath = path.join(catDir, entry.name, "routes.ts");
        if (fs.existsSync(routePath)) {
          routeProviders.push({ id: entry.name, category: cat });
          seenRouteIds.add(entry.name);
        }
      }
    }
  }

  routeProviders.sort((a, b) => a.id.localeCompare(b.id));

  console.log(`[codegen] Found ${routeProviders.length} provider route modules in src/providers/`);

  const importLines = routeProviders.map((p) => {
    const varName = `reg_${toSafeVar(p.id)}`;
    const relPath = p.category ? `../${p.category}/${p.id}/routes.js` : `../${p.id}/routes.js`;
    return `import { registerRoutes as ${varName} } from "${relPath}";`;
  });

  const registerCalls = routeProviders.map((p) => {
    const varName = `reg_${toSafeVar(p.id)}`;
    return `  ${varName}(router);`;
  });

  const routesRegistryContent = `// AUTO-GENERATED by scripts/generate-registries.mjs - DO NOT EDIT MANUALLY
import type { Router } from "express";

${importLines.join("\n")}

export function registerAllProviderRoutes(router: Router): void {
${registerCalls.join("\n")}
}
`;

  fs.writeFileSync(
    path.join(generatedDir, "routesRegistry.generated.ts"),
    routesRegistryContent,
    "utf8"
  );
}

const startTime = Date.now();
generateProviders();
generateProviderRoutes();
generateMitmHandlers();
generateCliTools();
console.log(`[codegen] Successfully generated all registries in ${Date.now() - startTime}ms`);
